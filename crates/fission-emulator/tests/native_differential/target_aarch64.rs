fn curated() -> Vec<Curated> {
    CURATED
        .iter()
        .map(|(name, bytes)| Curated {
            name: (*name).to_string(),
            bytes: bytes.to_vec(),
        })
        .collect()
}

fn buffer_pointer(rng: &mut Rng, align: u64) -> u64 {
    let off = BUF_LEN as u64 / 4 + rng.below(BUF_LEN as u64 / 2);
    (buf_addr() + off) & !(align - 1)
}

fn state(rng: &mut Rng, curated: Option<&str>) -> CpuState {
    let mut s = CpuState::zeroed();
    for i in 0..31 {
        s.gpr[i] = if rng.chance(30) {
            buffer_pointer(rng, 1)
        } else {
            int_value(rng)
        };
    }
    if ISA.ignored_gprs & (1 << 18) != 0 {
        s.gpr[18] = 0;
    }
    // SP must stay 16-byte aligned to be used as a base (Arm ARM D1.8.2).
    s.gpr[SP] = buffer_pointer(rng, 16);
    for f in 0..4 {
        s.flags[f] = rng.below(2) as u8;
    }
    for v in 0..32 {
        s.vec[v] = vec_value(rng);
    }
    rng.fill(&mut s.buf);
    if let Some(name) = curated {
        s.gpr[X1] = buffer_pointer(rng, 16);
        // Rounding instructions get a halfway input half the time: ties are
        // where the rounding modes differ, and a random float is almost never one.
        if (name.starts_with("frint") || name.starts_with("fcvt")) && rng.chance(50) {
            let tie = (rng.below(16) as f64 + 0.5) * if rng.chance(50) { -1.0 } else { 1.0 };
            if name.contains("s1") {
                s.vec[1][..4].copy_from_slice(&(tie as f32).to_bits().to_le_bytes());
            } else {
                s.vec[1][..8].copy_from_slice(&tie.to_bits().to_le_bytes());
            }
        }
    }
    s
}

fn random_insn(rng: &mut Rng) -> Vec<u8> {
    (rng.next_u64() as u32).to_le_bytes().to_vec()
}

fn skip(_bytes: &[u8], lifted: &Lifted, fission: &FissionMachine) -> Option<String> {
    let rs = fission.register_space;
    // System registers, except NZCV, FPCR and FPSR (0x1030..0x1048):
    // TPIDR_EL0 is the host's thread pointer, the counters are time, and the
    // rest trap at EL0.
    if touches_registers(&lifted.ops, rs, 0x1000, 0x1030, false)
        || touches_registers(&lifted.ops, rs, 0x1048, 0x3000, false)
    {
        return Some("system register".into());
    }
    // SVE: anything that reads a Z register beyond its low 128 bits, writes
    // there with anything but a zero-extension, or touches a predicate. The
    // spec writes every scalar and NEON result and then zeroes the rest of Zd
    // (zext or COPY 0, as the architecture does), which is not SVE and is compared;
    // treating any upper-Z access as SVE once skipped every FRINT and FCVT.
    let upper_z = |v: &fission_pcode_ir::ir::Varnode| {
        !v.is_constant
            && v.space_id == rs
            && (0x5000..0x5400).contains(&v.offset)
            && (v.offset - 0x5000) % 32 + u64::from(v.size) > 16
    };
    for op in &lifted.ops {
        let zero_extends = op.opcode == fission_pcode_ir::ir::PcodeOpcode::IntZExt
            || (op.opcode == fission_pcode_ir::ir::PcodeOpcode::Copy
                && op
                    .inputs
                    .first()
                    .is_some_and(|v| v.is_constant && v.constant_val == 0));
        if op.inputs.iter().any(upper_z)
            || (op.output.as_ref().is_some_and(upper_z) && !zero_extends)
        {
            return Some("sve".into());
        }
    }
    if touches_registers(&lifted.ops, rs, 0x6000, 0x7000, false) {
        return Some("sve".into());
    }
    let mn = lifted.mnemonic.as_str();
    // Exclusive monitors can fail spuriously on hardware (Arm ARM B2.9).
    if ["LDX", "STX", "LDAX", "STLX"]
        .iter()
        .any(|p| mn.starts_with(p))
    {
        return Some(format!("denied:{mn}"));
    }
    None
}

