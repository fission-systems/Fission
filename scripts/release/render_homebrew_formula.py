#!/usr/bin/env python3
"""Render the Homebrew formula for a release from its archive checksums.

    render_homebrew_formula.py <tag> <dir-with-.sha256-files> [--repo owner/name]

Reads `fission-<target>.tar.gz.sha256` for the four Unix targets and prints
`fission-cli.rb` on stdout. It is `fission-cli`, not `fission`, because
Homebrew already has an unrelated cask named `fission`.

The formula installs into the prefix layout the
archives already use (`bin/fission_cli`, `share/fission/...`), which the
binary resolves on its own as `exe_parent/../share/fission`.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

TARGETS = {
    ("macos", "arm"): "aarch64-apple-darwin",
    ("macos", "intel"): "x86_64-apple-darwin",
    ("linux", "arm"): "aarch64-unknown-linux-gnu",
    ("linux", "intel"): "x86_64-unknown-linux-gnu",
}

SHA_RE = re.compile(r"^([0-9a-f]{64})\b")


def read_sha(directory: Path, target: str) -> str:
    path = directory / f"fission-{target}.tar.gz.sha256"
    text = path.read_text(encoding="utf-8").strip()
    match = SHA_RE.match(text)
    if not match:
        raise SystemExit(f"{path}: no sha256 at the start of {text!r}")
    return match.group(1)


def render(tag: str, repo: str, shas: dict[tuple[str, str], str]) -> str:
    version = tag[1:] if tag.startswith("v") else tag
    base = f"https://github.com/{repo}/releases/download/{tag}"

    def block(os_name: str) -> str:
        lines = [f"  on_{os_name} do"]
        for cpu in ("arm", "intel"):
            target = TARGETS[(os_name, cpu)]
            lines += [
                f"    on_{cpu} do",
                f'      url "{base}/fission-{target}.tar.gz"',
                f'      sha256 "{shas[(os_name, cpu)]}"',
                "    end",
            ]
        lines.append("  end")
        return "\n".join(lines)

    return f'''# Generated by scripts/release/render_homebrew_formula.py for {tag}; do not edit by hand.
class FissionCli < Formula
  desc "Agent-first binary analysis and decompilation CLI"
  homepage "https://github.com/{repo}"
  version "{version}"
  license "Apache-2.0"

{block("macos")}

{block("linux")}

  def install
    bin.install "bin/fission_cli"
    (share/"fission").install Dir["share/fission/*"]
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/fission_cli --version")
    status = shell_output("#{{bin}}/fission_cli resources status --json")
    assert_match "share/fission/signatures", status
  end
end
'''


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("tag")
    parser.add_argument("checksum_dir", type=Path)
    parser.add_argument("--repo", default="fission-systems/Fission")
    args = parser.parse_args()
    shas = {key: read_sha(args.checksum_dir, target) for key, target in TARGETS.items()}
    sys.stdout.write(render(args.tag, args.repo, shas))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
