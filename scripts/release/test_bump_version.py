import tempfile
import unittest
from pathlib import Path

import bump_version

ROOT_TOML = """[workspace]
resolver = "2"
members = [
    "crates/a",
    "crates/b",
]

[profile.release]
lto = true
"""

CRATE_TOML = """[package]
name = "{name}"
version = "0.4.0"
edition = "2021"

[dependencies]
serde = {{ version = "1.0.0" }}
"""

LOCK = """# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "a"
version = "0.4.0"
dependencies = [
 "serde",
]

[[package]]
name = "b"
version = "0.4.0"

[[package]]
name = "b"
version = "0.4.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "00"

[[package]]
name = "serde"
version = "1.0.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
"""

MKDOCS = """nav:
  - Release Notes:
    - Fission 0.4.0: changelog/v0.4.0.md
    - Fission 0.3.0: changelog/v0.3.0.md
"""


class BumpTests(unittest.TestCase):
    def setUp(self):
        self.dir = tempfile.TemporaryDirectory()
        self.root = Path(self.dir.name)
        (self.root / "Cargo.toml").write_text(ROOT_TOML)
        for name in ("a", "b"):
            crate = self.root / "crates" / name
            crate.mkdir(parents=True)
            (crate / "Cargo.toml").write_text(CRATE_TOML.format(name=name))
        (self.root / "Cargo.lock").write_text(LOCK)
        (self.root / "mkdocs.yml").write_text(MKDOCS)

    def tearDown(self):
        self.dir.cleanup()

    def snapshot(self):
        return {p: p.read_text() for p in sorted(self.root.rglob("*")) if p.is_file()}

    def test_bumps_members_lock_and_nav(self):
        bump_version.bump(self.root, "v0.5.0")
        for name in ("a", "b"):
            text = (self.root / "crates" / name / "Cargo.toml").read_text()
            self.assertIn('version = "0.5.0"', text)
            # A dependency's version is not the package's.
            self.assertIn('serde = { version = "1.0.0" }', text)
        lock = (self.root / "Cargo.lock").read_text()
        self.assertEqual(lock.count('version = "0.5.0"'), 2)
        # A registry crate that shares a member's name keeps its version.
        self.assertIn('name = "b"\nversion = "0.4.0"\nsource = "registry', lock)
        self.assertIn('version = "1.0.0"', lock)
        self.assertIn("version = 4\n", lock)
        nav = (self.root / "mkdocs.yml").read_text()
        self.assertIn(
            "    - Fission 0.5.0: changelog/v0.5.0.md\n    - Fission 0.4.0: changelog/v0.4.0.md", nav
        )

    def test_running_twice_changes_nothing_the_second_time(self):
        bump_version.bump(self.root, "0.5.0")
        first = self.snapshot()
        bump_version.bump(self.root, "0.5.0")
        self.assertEqual(self.snapshot(), first)

    def test_rejects_a_version_that_is_not_semver(self):
        with self.assertRaises(SystemExit):
            bump_version.bump(self.root, "0.5")


if __name__ == "__main__":
    unittest.main()
